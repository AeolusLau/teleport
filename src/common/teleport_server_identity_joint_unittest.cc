// Cross-repo round-trip: a blob minted by fairyland (dev root PRIVATE key) must
// verify under the client lib with the dev PUBLIC key. Proves wire + signature
// compatibility across the two repos. The test injects a fixed 'now' well before
// the fixture's far-future expiry.
TEST(TeleportServerIdentityJointTest, VerifiesFairylandMintedDevBlob) {
  auto parts = ParseServerIdentityContainer(kFairylandMintedBlob);
  ASSERT_TRUE(parts);
  EXPECT_TRUE(VerifyServerIdentity(parts->signed_bytes, parts->signature,
                                   kDevRootKeyDer, "fairyland.io",
                                   base::Time::FromTimeT(1750000000)));
  // Negative: a genuine blob must still fail for a mismatched candidate domain.
  EXPECT_FALSE(VerifyServerIdentity(parts->signed_bytes, parts->signature,
                                    kDevRootKeyDer, "evil.example",
                                    base::Time::FromTimeT(1750000000)));
}

// --- Root-set aggregation ------------------------------------------------
//
// A release build trusts a primary and a dormant recovery root, and the server
// signs with whichever is currently active. The client therefore cannot assume
// the primary produced the signature it is holding.

TEST(TeleportServerIdentityRootSetTest, AcceptsASignatureFromANonFirstRoot) {
  auto parts = ParseServerIdentityContainer(kFairylandMintedBlob);
  ASSERT_TRUE(parts);
  const std::vector<std::string> roots = {
      std::string(reinterpret_cast<const char*>(kStagingRootKeyDer),
                  sizeof(kStagingRootKeyDer)),
      std::string(reinterpret_cast<const char*>(kDevRootKeyDer),
                  sizeof(kDevRootKeyDer))};
  EXPECT_EQ(VerifyAgainstRootSet(parts->signed_bytes, parts->signature, roots,
                                 "fairyland.io",
                                 base::Time::FromTimeT(1750000000)),
            ServerIdentityVerdict::kValid);
}

TEST(TeleportServerIdentityRootSetTest, RejectsWhenNoRootMatches) {
  auto parts = ParseServerIdentityContainer(kFairylandMintedBlob);
  ASSERT_TRUE(parts);
  const std::vector<std::string> roots = {
      std::string(reinterpret_cast<const char*>(kStagingRootKeyDer),
                  sizeof(kStagingRootKeyDer))};
  EXPECT_EQ(VerifyAgainstRootSet(parts->signed_bytes, parts->signature, roots,
                                 "fairyland.io",
                                 base::Time::FromTimeT(1750000000)),
            ServerIdentityVerdict::kBadSignature);
}

TEST(TeleportServerIdentityRootSetTest, EmptySetRejects) {
  auto parts = ParseServerIdentityContainer(kFairylandMintedBlob);
  ASSERT_TRUE(parts);
  EXPECT_EQ(VerifyAgainstRootSet(parts->signed_bytes, parts->signature, {},
                                 "fairyland.io",
                                 base::Time::FromTimeT(1750000000)),
            ServerIdentityVerdict::kBadSignature);
}

// The aggregation rule that matters. A blob whose signature is fine but whose
// domain does not match must report kDomainMismatch, NOT kBadSignature -- even
// though a non-matching root in the same set does produce kBadSignature. The
// naive "keep the last verdict" implementation reports a key problem that does
// not exist, and the historical symptom of a verification failure here is a
// silent hang on "Completing enrollment..." (2026-07-04), so an operator sent
// hunting the wrong cause pays for it in hours.
TEST(TeleportServerIdentityRootSetTest, ReportsFieldFailureNotSignatureFailure) {
  auto parts = ParseServerIdentityContainer(kFairylandMintedBlob);
  ASSERT_TRUE(parts);
  const std::vector<std::string> roots = {
      std::string(reinterpret_cast<const char*>(kStagingRootKeyDer),
                  sizeof(kStagingRootKeyDer)),
      std::string(reinterpret_cast<const char*>(kDevRootKeyDer),
                  sizeof(kDevRootKeyDer))};
  EXPECT_EQ(VerifyAgainstRootSet(parts->signed_bytes, parts->signature, roots,
                                 "evil.example",
                                 base::Time::FromTimeT(1750000000)),
            ServerIdentityVerdict::kDomainMismatch);
}

